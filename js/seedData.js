export function seedQuestions() {
  const bank = {
    t_philosophy: ["What is the primary focus of metaphysics?", "Who wrote 'Critique of Pure Reason'?", "Define 'a priori' knowledge.", "What is the Socratic method?"],
    t_ethics: ["What is the categorical imperative?", "Define utilitarianism.", "Who proposed the veil of ignorance?", "What is virtue ethics?"],
    t_epistemology: ["What is justified true belief?", "Define skepticism.", "What is empiricism?", "Who is known for cogito ergo sum?"],
    t_metaphysics: ["What is ontology?", "Define free will vs determinism.", "What is substance dualism?", "What is the problem of universals?"],
    t_logic: ["What is a syllogism?", "Define modus ponens.", "What is a fallacy?", "What does 'reductio ad absurdum' mean?"]
  };
  const topicNames = { t_philosophy: 'Philosophy', t_ethics: 'Ethics', t_epistemology: 'Epistemology', t_metaphysics: 'Metaphysics', t_logic: 'Logic' };
  let counter = 0;
  const out = [];
  for (const topicId in bank) {
    bank[topicId].forEach((qText, i) => {
      counter++;
      out.push({
        id: 'q_seed_' + counter,
        courseId: 'c_law',
        topicId,
        q: `${qText} (${topicNames[topicId]} example ${i + 1})`,
        options: ["Option A: Correct perspective", "Option B: Alternative view", "Option C: Another theory", "Option D: Counter argument"],
        answer: "Option A: Correct perspective",
        explanation: `This illustrates a core idea within ${topicNames[topicId]} — Option A represents the standard, correct perspective covered in class.`
      });
    });
  }
  return out;
}

